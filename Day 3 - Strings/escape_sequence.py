a = "Aman \n Bhopal" #New line is used to print the string in new line. If we use single quote to print the string with new line then it will give error.

b = "Aman \t Bhopal" #Tab

c = "Aman \\ Bhopal" #Backslash is used to print the string with backslash. If we use single quote to print the string with backslash then it will give error.

d = "Aman \' Bhopal" #Single quote is used to print the string with single quote. If we use double quote to print the string with single quote then it will give error.

e = "Aman \"Bhopal\"" #Double quote is used to print the string with single quote. If we use single quote to print the string with single quote then it will give error.

f = "Aman \b Bhopal" #Backspace

g = "Aman \r Bhopal" #Carriage return


print(a)    
print(b)
print(c)
print(d)
print(e)
print(f)
print(g)